def search_airports(query: str, limit: int = 10) -> List[Dict]:
    """
    Search airports by code, city name, airport name, or alias.

    Args:
        query: Search term (code, city, name, or alias)
        limit: Maximum results to return

    Returns:
        List of matching airport dicts with code, name, city, country
    """
    if not query or len(query) < 2:
        return []

    query = query.upper().strip()
    results = []
    seen_codes = set()

    # First check if query matches any city aliases
    if query in CITY_ALIASES:
        for code in CITY_ALIASES[query]:
            if code in AIRPORTS and code not in seen_codes:
                data = AIRPORTS[code]
                results.append({
                    "code": code,
                    "name": data["name"],
                    "city": data["city"],
                    "country": data["country"],
                    "country_code": data["country_code"],
                    "score": 95,  # High score for alias match
                    "display": f"{code} - {data['city']}, {data['country']} ({data['name']})"
                })
                seen_codes.add(code)

    # Also check partial alias matches
    for alias, codes in CITY_ALIASES.items():
        if alias.startswith(query) or query in alias:
            for code in codes:
                if code in AIRPORTS and code not in seen_codes:
                    data = AIRPORTS[code]
                    results.append({
                        "code": code,
                        "name": data["name"],
                        "city": data["city"],
                        "country": data["country"],
                        "country_code": data["country_code"],
                        "score": 75 if alias.startswith(query) else 55,
                        "display": f"{code} - {data['city']}, {data['country']} ({data['name']})"
                    })
                    seen_codes.add(code)

    # Then search the main airport database
    for code, data in AIRPORTS.items():
        if code in seen_codes:
            continue

        score = 0

        # Exact code match (highest priority)
        if code == query:
            score = 100
        # Code starts with query
        elif code.startswith(query):
            score = 80
        # City name starts with query
        elif data["city"].upper().startswith(query):
            score = 70
        # City contains query
        elif query in data["city"].upper():
            score = 50
        # Airport name contains query
        elif query in data["name"].upper():
            score = 40
        # Country contains query
        elif query in data["country"].upper():
            score = 30

        if score > 0:
            results.append({
                "code": code,
                "name": data["name"],
                "city": data["city"],
                "country": data["country"],
                "country_code": data["country_code"],
                "score": score,
                "display": f"{code} - {data['city']}, {data['country']} ({data['name']})"
            })
            seen_codes.add(code)

    # Sort by score (descending) then by city name
    results.sort(key=lambda x: (-x["score"], x["city"]))

    return results[:limit]


def get_airport(code: str) -> Optional[Dict]:
    """Get airport data by code."""
    code = code.upper().strip()
    if code in AIRPORTS:
        data = AIRPORTS[code]
        return {
            "code": code,
            "name": data["name"],
            "city": data["city"],
            "country": data["country"],
            "country_code": data["country_code"]
        }
    return None


def get_country_code(airport_code: str) -> Optional[str]:
    """Get country code for an airport."""
    airport = get_airport(airport_code)
    return airport["country_code"] if airport else None


